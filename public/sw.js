/**
 * Offline service worker.
 *
 * The app is used on planes, just after landing abroad, and in remote places
 * with no signal, so every page has to stay browsable from the last sync. That
 * is tractable here because every page is a client component that fetches JSON
 * from /api/... — there is no server-rendered trip data to reproduce. Caching
 * the HTML shells, the Next build assets, and the GET responses is enough.
 *
 * The keystone is /api/auth/session. Every page gates on useSession(), and
 * next-auth treats a failed session fetch as "signed out", which redirects to /.
 * Without that response cached, no amount of cached trip data renders.
 *
 * Deliberately hand-rolled rather than generated by a build plugin: the only
 * thing those really buy is a precache manifest, and the explicit warm-up below
 * covers the same ground without coupling to the build.
 */

const CACHE_VERSION = "v2"
const SHELL_CACHE = `trip-planner-shell-${CACHE_VERSION}`
const STATIC_CACHE = `trip-planner-static-${CACHE_VERSION}`
const API_CACHE = `trip-planner-api-${CACHE_VERSION}`
const APP_CACHES = [SHELL_CACHE, STATIC_CACHE, API_CACHE]

const CACHED_AT_HEADER = "sw-cached-at"

/** Fallback shell for a navigation we have never cached. */
const FALLBACK_SHELL = "/trips"

/**
 * API GETs are cacheable by default so new read endpoints work without touching
 * this file. The exceptions are endpoints that are meaningless or harmful when
 * replayed from cache: they either need the network anyway (search, AI, route
 * geometry, extraction), stream a file, or carry a single-use token.
 */
function isCacheableApi(url) {
  if (!url.pathname.startsWith("/api/")) return false

  // Session is the one auth route worth caching. Never cache csrf/providers/
  // callback — a stale csrf token breaks sign-in.
  if (url.pathname.startsWith("/api/auth/")) {
    return url.pathname === "/api/auth/session"
  }

  const networkOnly = [
    "/api/ai/",
    "/api/routes",
    "/api/extract",
  ]
  if (networkOnly.some((p) => url.pathname.startsWith(p))) return false

  const networkOnlySuffixes = ["/discover", "/export", "/translate", "/extract"]
  if (networkOnlySuffixes.some((s) => url.pathname.endsWith(s))) return false

  return true
}

function isStaticAsset(url) {
  return (
    url.pathname.startsWith("/_next/static/") ||
    url.pathname.startsWith("/icons/") ||
    /\.(?:woff2?|ttf|otf|png|svg|ico|webp)$/.test(url.pathname)
  )
}

/**
 * Next's client router requests RSC payloads for the same path with a rotating
 * `_rsc` hash, so they are cached and matched with the query stripped.
 */
function isRscRequest(request, url) {
  return request.headers.get("RSC") === "1" || url.searchParams.has("_rsc")
}

function rscCacheKey(url) {
  return `${url.origin}${url.pathname}?__rsc=1`
}

/** Copy a response, stamping when it was stored so the UI can show a sync age. */
async function withCachedAt(response) {
  const headers = new Headers(response.headers)
  headers.set(CACHED_AT_HEADER, new Date().toISOString())
  return new Response(await response.blob(), {
    status: response.status,
    statusText: response.statusText,
    headers,
  })
}

async function putInCache(cacheName, key, response) {
  if (!response || !response.ok) return
  const cache = await caches.open(cacheName)
  await cache.put(key, await withCachedAt(response.clone()))
}

function offlineResponse() {
  return new Response(JSON.stringify({ error: "offline" }), {
    status: 503,
    headers: { "Content-Type": "application/json" },
  })
}

// --- Strategies ---------------------------------------------------------

async function cacheFirst(request, cacheName) {
  const cached = await caches.match(request, { cacheName })
  if (cached) return cached
  try {
    const response = await fetch(request)
    await putInCache(cacheName, request, response)
    return response
  } catch {
    return offlineResponse()
  }
}

async function networkFirst(request, cacheName, cacheKey = request) {
  try {
    const response = await fetch(request)
    await putInCache(cacheName, cacheKey, response)
    return response
  } catch {
    const cached = await caches.match(cacheKey, { cacheName })
    if (cached) return cached
    return offlineResponse()
  }
}

/**
 * Answer from cache immediately and refresh in the background.
 *
 * Network-first was the wrong trade for how this app is actually used. On hotel
 * wifi or a roaming signal the network does not fail cleanly — it hangs — so
 * every screen paid the full timeout before falling back to a cached copy it had
 * all along. Serving the cached copy first makes an opened trip instant, and the
 * cost is that a change someone else made lands one interaction late.
 *
 * Returns the background fetch as `revalidation` so the caller can keep the
 * worker alive for it via `event.waitUntil`.
 */
function staleWhileRevalidate(request, cacheName, cacheKey = request) {
  // putInCache clones internally, so the response handed back is still unread.
  const network = fetch(request)
    .then(async (response) => {
      await putInCache(cacheName, cacheKey, response)
      return response
    })
    .catch(() => null)

  const response = caches.match(cacheKey, { cacheName }).then(async (cached) => {
    if (cached) {
      notifyRevalidating(cacheKey)
      return cached
    }
    return await network
  })

  return { response, revalidation: network }
}

/**
 * Tells the app a screen is showing cached data while it refreshes, so it can
 * say so rather than looking silently out of date.
 */
async function notifyRevalidating(cacheKey) {
  const url = typeof cacheKey === "string" ? cacheKey : cacheKey.url
  const clients = await self.clients.matchAll({ type: "window" })
  for (const client of clients) {
    client.postMessage({ type: "REVALIDATING", url })
  }
}

function handleNavigation(request) {
  const url = new URL(request.url)
  const { response, revalidation } = staleWhileRevalidate(request, SHELL_CACHE, url.pathname)

  return {
    response: response.then(async (res) => {
      // `res` is null only when nothing was cached and the network failed: a
      // route we never warmed, opened offline. The trip list is the useful
      // entry point, and every page shell is interchangeable enough to get the
      // user somewhere they can navigate from.
      if (res) return res
      const fallback = await caches.match(FALLBACK_SHELL, { cacheName: SHELL_CACHE })
      if (fallback) return fallback
      return new Response("Offline", { status: 503, headers: { "Content-Type": "text/plain" } })
    }),
    revalidation,
  }
}

// --- Warm-up ------------------------------------------------------------

const NEXT_ASSET_RE = /\/_next\/static\/[^"'\s\\)>]+/g

/**
 * Warming a shell caches its HTML but not the JS that makes it run, so a route
 * the user never opened online would render nothing offline. Scrape the asset
 * URLs out of the HTML (and the font URLs out of the CSS it references) and
 * cache those too.
 */
async function cacheReferencedAssets(html) {
  const urls = new Set(html.match(NEXT_ASSET_RE) || [])
  const cssUrls = [...urls].filter((u) => u.endsWith(".css"))

  await Promise.all(
    cssUrls.map(async (href) => {
      try {
        const res = await fetch(href)
        if (!res.ok) return
        const text = await res.text()
        for (const found of text.match(NEXT_ASSET_RE) || []) urls.add(found)
      } catch {
        // A missing stylesheet just means fewer fonts offline.
      }
    })
  )

  const cache = await caches.open(STATIC_CACHE)
  await Promise.all(
    [...urls].map(async (href) => {
      if (await cache.match(href)) return
      try {
        const res = await fetch(href)
        if (res.ok) await cache.put(href, res)
      } catch {
        // Best effort.
      }
    })
  )
}

async function warmUrl(url) {
  const parsed = new URL(url, self.location.origin)
  try {
    const response = await fetch(parsed.href, { credentials: "same-origin" })
    if (!response.ok) return

    if (parsed.pathname.startsWith("/api/")) {
      await putInCache(API_CACHE, parsed.href, response)
      return
    }

    await putInCache(SHELL_CACHE, parsed.pathname, response.clone())
    await cacheReferencedAssets(await response.text())
  } catch {
    // Warm-up is opportunistic; the next online visit tries again.
  }
}

async function warm(urls) {
  // Sequential on purpose: this runs on page load over what may be a weak
  // connection, and a burst of parallel requests would compete with the UI.
  for (const url of urls) {
    await warmUrl(url)
  }
}

async function purge() {
  const names = await caches.keys()
  await Promise.all(
    names.filter((n) => n.startsWith("trip-planner-")).map((n) => caches.delete(n))
  )
}

// --- Lifecycle ----------------------------------------------------------

self.addEventListener("install", (event) => {
  event.waitUntil(self.skipWaiting())
})

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys()
      await Promise.all(
        names
          .filter((n) => n.startsWith("trip-planner-") && !APP_CACHES.includes(n))
          .map((n) => caches.delete(n))
      )
      await self.clients.claim()
    })()
  )
})

self.addEventListener("fetch", (event) => {
  const { request } = event

  // Mutations must never be served or recorded from cache. The offline queue in
  // the app handles the one write that survives a lost connection.
  if (request.method !== "GET") return

  const url = new URL(request.url)
  if (url.origin !== self.location.origin) return

  if (isStaticAsset(url)) {
    event.respondWith(cacheFirst(request, STATIC_CACHE))
    return
  }

  if (isRscRequest(request, url)) {
    event.respondWith(networkFirst(request, SHELL_CACHE, rscCacheKey(url)))
    return
  }

  if (request.mode === "navigate") {
    const { response, revalidation } = handleNavigation(request)
    event.respondWith(response)
    // The page has already been answered from cache by then, so the refresh
    // needs the worker kept alive on its own account.
    event.waitUntil(revalidation)
    return
  }

  if (isCacheableApi(url)) {
    const { response, revalidation } = staleWhileRevalidate(request, API_CACHE)
    event.respondWith(response.then((res) => res ?? offlineResponse()))
    event.waitUntil(revalidation)
  }
})

self.addEventListener("message", (event) => {
  const data = event.data
  if (!data || typeof data !== "object") return

  if (data.type === "WARM" && Array.isArray(data.urls)) {
    event.waitUntil(warm(data.urls))
    return
  }

  if (data.type === "PURGE") {
    event.waitUntil(purge())
  }
})
